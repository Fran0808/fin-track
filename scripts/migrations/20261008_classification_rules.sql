BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE IF NOT EXISTS classification_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    match_text VARCHAR(150) NOT NULL CHECK (length(btrim(match_text)) > 0),
    category_id BIGINT NOT NULL REFERENCES categories(id),
    priority INTEGER NOT NULL CHECK (priority BETWEEN 0 AND 9999),
    enabled BOOLEAN NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_rule_user_priority
    ON classification_rules (user_id, priority, id);

COMMIT;
