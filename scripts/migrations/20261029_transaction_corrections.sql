BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
CREATE UNIQUE INDEX IF NOT EXISTS idx_tx_id_user ON transactions(id,user_id);
CREATE TABLE IF NOT EXISTS transaction_corrections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id),
    request_id VARCHAR(36) NOT NULL,
    expected_revision BIGINT NOT NULL CHECK (expected_revision >= 0),
    reason VARCHAR(300) NOT NULL CHECK (length(trim(reason)) > 0),
    before_amount NUMERIC(10,2) NOT NULL CHECK (before_amount > 0),
    after_amount NUMERIC(10,2) NOT NULL CHECK (after_amount > 0),
    before_date TIMESTAMP NOT NULL,
    after_date TIMESTAMP NOT NULL,
    before_flow VARCHAR(20) NOT NULL CHECK (before_flow IN ('EXPENSE','INCOME','INTERNAL_TRANSFER')),
    after_flow VARCHAR(20) NOT NULL CHECK (after_flow IN ('EXPENSE','INCOME','INTERNAL_TRANSFER')),
    before_operation VARCHAR(32) NOT NULL CHECK (before_operation IN ('UNKNOWN','OWN_CARD_PAYMENT')),
    after_operation VARCHAR(32) NOT NULL CHECK (after_operation IN ('UNKNOWN','OWN_CARD_PAYMENT')),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_correction_owner FOREIGN KEY (transaction_id,user_id) REFERENCES transactions(id,user_id),
    CONSTRAINT uq_correction_request UNIQUE (transaction_id,request_id),
    CONSTRAINT chk_correction_operation CHECK (
        (before_operation <> 'OWN_CARD_PAYMENT' OR before_flow = 'INTERNAL_TRANSFER') AND
        (after_operation <> 'OWN_CARD_PAYMENT' OR after_flow = 'INTERNAL_TRANSFER'))
);
CREATE INDEX IF NOT EXISTS idx_correction_history ON transaction_corrections(user_id,transaction_id,id DESC);
COMMIT;
