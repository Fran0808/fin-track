-- New, empty PostgreSQL databases only. Existing installations use incremental migrations.
-- No IF NOT EXISTS: any existing application table aborts this entire transaction.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(150) NOT NULL UNIQUE,
    full_name VARCHAR(200), picture_url TEXT, google_sub_id VARCHAR(100),
    device_pairing_token VARCHAR(64) UNIQUE,
    created_at TIMESTAMP NOT NULL, last_login_at TIMESTAMP
);
CREATE UNIQUE INDEX idx_user_email ON users(email);
CREATE UNIQUE INDEX idx_user_pairing_token ON users(device_pairing_token);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id), name VARCHAR(100) NOT NULL,
    icon VARCHAR(50), color VARCHAR(20), is_system BOOLEAN NOT NULL,
    active BOOLEAN NOT NULL, parent_id BIGINT REFERENCES categories(id)
);
CREATE INDEX idx_category_user_active ON categories(user_id, active);
CREATE INDEX idx_category_user_system ON categories(user_id, is_system);
CREATE INDEX idx_category_parent ON categories(parent_id);

CREATE TABLE financial_instruments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id), type VARCHAR(20) NOT NULL,
    alias VARCHAR(100) NOT NULL, bank VARCHAR(20) NOT NULL,
    institution_name VARCHAR(100), last_four VARCHAR(4),
    currency VARCHAR(3) NOT NULL, active BOOLEAN NOT NULL,
    linked_account_id BIGINT REFERENCES financial_instruments(id)
);
CREATE INDEX idx_instrument_user_active ON financial_instruments(user_id, active);
CREATE INDEX idx_instrument_linked_account ON financial_instruments(linked_account_id);

CREATE TABLE classification_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id), match_text VARCHAR(150) NOT NULL,
    category_id BIGINT NOT NULL REFERENCES categories(id), priority INTEGER NOT NULL,
    enabled BOOLEAN NOT NULL
);
CREATE INDEX idx_rule_user_priority ON classification_rules(user_id, priority, id);

CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id), financial_instrument_id BIGINT REFERENCES financial_instruments(id),
    amount NUMERIC(10,2) NOT NULL, flow_type VARCHAR(20) NOT NULL,
    contact_name VARCHAR(150) NOT NULL, channel VARCHAR(50) NOT NULL, card_last4 VARCHAR(10),
    transaction_date TIMESTAMP NOT NULL, category VARCHAR(100), tags VARCHAR(255), notes VARCHAR(500),
    transaction_hash VARCHAR(64) NOT NULL, created_at TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX idx_tx_hash_user ON transactions(transaction_hash, user_id);
CREATE INDEX idx_tx_date ON transactions(transaction_date);
CREATE INDEX idx_tx_user ON transactions(user_id);
CREATE INDEX idx_tx_user_instrument_date ON transactions(user_id, financial_instrument_id, transaction_date);

CREATE TABLE raw_notification_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id), transaction_id BIGINT REFERENCES transactions(id),
    raw_text TEXT NOT NULL, source_package VARCHAR(100),
    received_at TIMESTAMP NOT NULL, is_processed BOOLEAN NOT NULL
);
CREATE TABLE google_oauth_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id), email VARCHAR(255) NOT NULL UNIQUE,
    access_token TEXT NOT NULL, refresh_token TEXT, expires_at TIMESTAMP NOT NULL,
    scope VARCHAR(255), last_synced_internal_date BIGINT,
    last_successful_sync_at TIMESTAMP WITH TIME ZONE, last_sync_failed BOOLEAN,
    created_at TIMESTAMP, updated_at TIMESTAMP
);
CREATE TABLE processed_email_messages (
    message_id VARCHAR(100) PRIMARY KEY, internal_date_ms BIGINT,
    user_id BIGINT REFERENCES users(id),
    subject VARCHAR(255), created_at TIMESTAMP NOT NULL
);
COMMIT;
